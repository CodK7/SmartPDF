import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = process.cwd();
const files = {
  displayLatin: "newsreader-latin.woff2",
  displayArabic: "noto-naskh-arabic-700.woff2",
  bodyLatin: "noto-sans-latin.woff2",
  bodyArabic: "noto-sans-arabic.woff2",
};

const entries = await Promise.all(Object.entries(files).map(async ([key, file]) => {
  const value = (await readFile(resolve(root, "public", "fonts", file))).toString("base64");
  return `  ${key}: "${value}"`;
}));

await writeFile(
  resolve(root, "src", "infrastructure", "pdf", "generated-font-assets.ts"),
  `// Generated by scripts/generate-pdf-fonts.mjs. Do not edit manually.\nexport const EMBEDDED_PDF_FONT_ASSETS = {\n${entries.join(",\n")}\n} as const;\n`,
  "utf8",
);
